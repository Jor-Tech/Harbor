const {_electron:electron}=require('playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
(async()=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'harbor-ui-'));let app;
 try{
  app=await electron.launch({executablePath:process.env.HARBOR_EXECUTABLE||undefined,args:process.env.HARBOR_EXECUTABLE?['--disable-gpu']:['.','--disable-gpu'],env:{...process.env,HARBOR_DATA_DIR:dir}});
  const page=await app.firstWindow();page.setDefaultTimeout(10000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.getByRole('heading',{name:'Create your personal vault'}).waitFor();
  if(process.platform==='darwin'){
    await page.evaluate(()=>window.harbor.invoke('window:close'));
    await app.evaluate(({app})=>app.emit('activate'));
    await page.getByRole('heading',{name:'Create your personal vault'}).waitFor();
    assert.equal((await page.evaluate(()=>window.harbor.invoke('vault:status'))).exists,false);
  }
  await page.screenshot({path:'research/harbor-vault.png'});
  await page.getByLabel('Vault password',{exact:true}).fill('Harbor-test-password-2026');
  await page.getByLabel('Confirm password',{exact:true}).fill('Harbor-test-password-2026');
  await page.getByRole('button',{name:'Create vault',exact:true}).click();
  await page.getByRole('heading',{name:'Hosts',exact:true}).waitFor();
  await page.getByRole('button',{name:'New group',exact:true}).last().click();
  await page.getByLabel('Name',{exact:true}).fill('Production');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('heading',{name:'New group',exact:true}).waitFor({state:'hidden'});
  await page.getByRole('button',{name:'New host',exact:true}).click();
  await page.getByLabel('Label',{exact:true}).fill('Production web');
  await page.getByLabel('Address',{exact:true}).fill('web.example.test');
  await page.getByLabel('Username',{exact:true}).fill('deploy');
  await page.getByLabel('Group',{exact:true}).selectOption({label:'Production'});
  await page.getByLabel('Tags',{exact:true}).fill('production, web');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('heading',{name:'New host',exact:true}).waitFor({state:'hidden'});
  await page.evaluate(async()=>{for(const host of [{label:'Analytics database',address:'db.example.test',username:'postgres',tags:'database',color:'purple'},{label:'Development',address:'dev.example.test',username:'developer',tags:'development',color:'green'},{label:'Edge gateway',address:'edge.example.test',username:'admin',tags:'network',color:'orange'}])await window.harbor.invoke('entity:save',{collection:'hosts',item:{...host,port:22}})});
  // Exercise encrypted persistence by locking and unlocking through the UI.
  await page.getByTitle('Lock vault',{exact:true}).click();
  await page.getByRole('heading',{name:'Welcome back'}).waitFor();
  await page.getByLabel('Vault password',{exact:true}).fill('Harbor-test-password-2026');
  await page.getByRole('button',{name:'Unlock vault',exact:true}).click();
  await page.getByRole('heading',{name:'Hosts',exact:true}).waitFor();
  assert.equal(await page.locator('.host-card').count(),4);
  await page.screenshot({path:'research/harbor-hosts.png'});
  await page.locator('#search').fill('Analytics');
  assert.equal(await page.locator('.host-card').count(),1);
  await page.locator('#search').fill('');
  await page.getByRole('button',{name:'Snippets',exact:true}).click();
  await page.getByRole('button',{name:'New snippet',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Disk usage');
  await page.getByLabel('Command',{exact:true}).fill('df -h');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByText('Disk usage',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Keychain',exact:true}).click();
  await page.getByRole('button',{name:'New key',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Test Ed25519');
  await page.getByRole('button',{name:'Generate Ed25519 key',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Private key"]')?.value.includes('BEGIN OPENSSH PRIVATE KEY'));
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByText('Test Ed25519',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  assert.equal(await page.locator('.about strong span').innerText(),await app.evaluate(({app})=>app.getVersion()));
  await page.locator('.setting-row').filter({hasText:'Appearance'}).locator('select').selectOption('light');
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='light');
  await page.locator('.setting-row').filter({hasText:'Appearance'}).locator('select').selectOption('dark');
  await page.getByRole('button',{name:'Vault & sync',exact:false}).click();
  const syncDir=path.join(dir,'sync');await fs.mkdir(syncDir);
  await app.evaluate(({dialog},syncDir)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[syncDir]})},syncDir);
  await page.getByRole('button',{name:'Choose folder',exact:true}).click();
  await page.getByRole('button',{name:'Sync now',exact:true}).click();
  await page.locator('.sync-status small').filter({hasText:'· pushed'}).waitFor();
  const shared=(await fs.readdir(syncDir)).find(n=>n.endsWith('.harbor-vault'));
  assert(shared,'Encrypted shared vault was created');
  const {Vault}=require('../electron/vault.cjs');
  const replica=new Vault(path.join(dir,'replica.hbr'));await replica.importFrom(path.join(syncDir,shared),'Harbor-test-password-2026');
  let replicaData=await replica.read();assert.equal(replicaData.settings.syncFolder,undefined,'Sync folder must stay device-local');
  replicaData.groups.push({id:'remote-group',label:'Remote edit'});await replica.save(replicaData);await replica.sync(syncDir);
  await page.evaluate(()=>window.harbor.invoke('entity:save',{collection:'groups',item:{label:'Local edit'}}));
  await page.getByRole('button',{name:'Sync now',exact:true}).click();
  await page.getByText('Both copies changed',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Compare changes',exact:true}).click();
  await page.getByRole('button',{name:'Keep this device',exact:true}).click();
  await page.getByRole('button',{name:'Apply choices',exact:true}).click();
  await page.locator('.sync-status small').filter({hasText:'· resolved-items'}).waitFor();
  assert.equal((await replica.sync(syncDir)).status,'pulled');replica.lock();
  await page.screenshot({path:'research/harbor-sync.png'});
  await page.getByRole('button',{name:'Hosts',exact:false}).first().click();
  await page.getByRole('button',{name:'Local terminal',exact:true}).click();
  await page.locator('.terminal-pane:visible .xterm').waitFor();
  await page.evaluate(()=>{window.testTerminalOutput='';window.harbor.on('terminal:data',e=>window.testTerminalOutput+=e.data)});
  await page.locator('.xterm-helper-textarea').pressSequentially('echo HARBOR_SMOKE_OK\r',{delay:15});
  await page.waitForFunction(()=>window.testTerminalOutput.includes('HARBOR_SMOKE_OK'));
  await page.screenshot({path:'research/harbor-terminal.png'});
  assert.deepEqual(errors,[]);
  const stored=await fs.readFile(path.join(dir,'vault.hbr'),'utf8');assert(!stored.includes('web.example.test'));
  if(process.platform==='darwin'){
    await page.evaluate(()=>window.harbor.invoke('window:close'));
    assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isVisible()),false);
    await app.evaluate(({app})=>app.emit('activate'));
    await page.getByRole('heading',{name:'Welcome back'}).waitFor();
    assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isVisible()),true);
    assert.equal((await page.evaluate(()=>window.harbor.invoke('vault:status'))).locked,true);
  }
  console.log('PASS: vault creation, host/group CRUD, persistence, search, snippets, key generation, settings, sync conflict resolution, local terminal and renderer errors.');
 }finally{await app?.close();await fs.rm(dir,{recursive:true,force:true})}
})().catch(e=>{console.error(e);process.exit(1)});
